public class Main {
    public static void main(String[] args) {
        int n1 = 10;
        int n2 = 30;
        int soma = n1 + n2;
        System.out.println("Soma = "+ soma);
        n1 = -30;
        n2 = 10;
        soma = n1 + n2;
        System.out.println("Soma = "+ soma);
        n1 = 0;
        n2 = 0;
        soma = n1 + n2;
        System.out.println("Soma = "+ soma);

    }
}